/** Replace tokens in a string. */
export function fillTokens(text, { venue, share }) {
  return text.replaceAll("{{VENUE}}", venue).replaceAll("{{SHARE}}", `${share}%`);
}

/** Canonical plain-text rendering, used for the SHA-256 integrity fingerprint. */
export function canonicalText(vals) {
  const a = AGREEMENT;
  const lines = [
    `${a.company.name} — ${a.title} — v${a.version}`,
    ...a.intro.map((p) => fillTokens(p, vals)),
  ];
  a.clauses.forEach((c, i) => {
    lines.push(`${i + 1}. ${c.title}`);
    c.paragraphs.forEach((p, j) => lines.push(`${i + 1}.${j + 1} ${fillTokens(p, vals)}`));
  });
  lines.push(fillTokens(a.acceptanceStatement, vals));
  return lines.join("\n");
}
