// Packs the whole app into a single Cloudflare Pages "_worker.js" that serves
// every file itself. This lets the app be published with one API request,
// without Cloudflare's separate file-upload step.
//
//   node deploy/build-worker.mjs <output-file>
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = process.argv[2] || join(APP, "_worker.js");

const INCLUDE = ["index.html", "manifest.webmanifest", "sw.js", "css", "js", "vendor", "icons"];
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".webmanifest": "application/manifest+json",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".txt": "text/plain; charset=utf-8",
};
const TEXT = new Set([".html", ".css", ".js", ".webmanifest", ".txt"]);

function walk(p) {
  const full = join(APP, p);
  if (statSync(full).isDirectory()) return readdirSync(full).flatMap((n) => walk(join(p, n)));
  return [p];
}

const files = {};
for (const f of INCLUDE.flatMap(walk)) {
  const ext = extname(f);
  if (!TYPES[ext]) continue;
  const buf = readFileSync(join(APP, f));
  files["/" + relative(".", f).split("\\").join("/")] = TEXT.has(ext)
    ? { t: TYPES[ext], s: buf.toString("utf8") }
    : { t: TYPES[ext], b: buf.toString("base64") };
}

const SECURITY = {
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "DENY",
  "Referrer-Policy": "no-referrer",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
  "Content-Security-Policy":
    "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; worker-src 'self' blob:; connect-src 'self'; object-src 'none'; base-uri 'self'; frame-ancestors 'none'",
};

const src = `// Generated by deploy/build-worker.mjs — do not edit.
const FILES = ${JSON.stringify(files)};
const SECURITY = ${JSON.stringify(SECURITY)};
const decoded = new Map();
function body(path, f) {
  if (f.s !== undefined) return f.s;
  if (!decoded.has(path)) decoded.set(path, Uint8Array.from(atob(f.b), (c) => c.charCodeAt(0)));
  return decoded.get(path);
}
export default {
  async fetch(request) {
    const url = new URL(request.url);
    let path = decodeURIComponent(url.pathname);
    if (path === "/" || path === "") path = "/index.html";
    const f = FILES[path];
    if (!f) return new Response("Not found", { status: 404, headers: SECURITY });
    const noCache = path === "/index.html" || path === "/sw.js" || path === "/manifest.webmanifest";
    return new Response(request.method === "HEAD" ? null : body(path, f), {
      headers: { ...SECURITY, "Content-Type": f.t, "Cache-Control": noCache ? "no-cache" : "public, max-age=3600" },
    });
  },
};
`;
writeFileSync(out, src);
console.log(`Wrote ${out}: ${Object.keys(files).length} files, ${(src.length / 1024).toFixed(0)} KB`);
